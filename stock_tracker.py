if __name__ == "__main__":
    conn = init_db()

    # ── Add sample alerts (edit to suit your needs) ──────────────────────
    add_alert(conn, "AAPL",  "above", 200.00)   # notify if Apple > $200
    add_alert(conn, "TSLA",  "below", 150.00)   # notify if Tesla < $150
    add_alert(conn, "GOOGL", "above", 180.00)   # notify if Google > $180

    # ── Start tracking ────────────────────────────────────────────────────
    track(
        symbols  = ["AAPL", "TSLA", "GOOGL", "MSFT"],
        interval = 60,       # seconds between each price check
        conn     = conn,
    )
